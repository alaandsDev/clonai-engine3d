import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdir, mkdtemp, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { asset, approval, pcmPlan, sine } from "../sound-fixtures";
import { MediaAssetRegistry, contentHash } from "../../src/sound/registry";
import { soundOutput, encodeWav, mixAudio, audioQa } from "../../src/sound/mixer";
import { ffmpegExecutable } from "../../src/sound/tools";
test("sound integration: controlled WAV voice + SFX → real mixer → WAV/ffprobe/QA/cache", async () => {
    const dir = soundOutput("tests");
    await mkdir(dir, { recursive: true });
    const root = await mkdtemp(path.join(dir, "mixer-")), ffmpeg = ffmpegExecutable(), voiceFile = path.join(root, "voice.wav"), sfxFile = path.join(root, "sfx.wav");
    await encodeWav(ffmpeg, sine(1, .2, 240), voiceFile);
    await encodeWav(ffmpeg, sine(.25, .5, 1800), sfxFile);
    const original = await readFile(sfxFile), a = asset();
    a.contentHash = contentHash(original);
    a.technicalMetadata.sizeBytes = original.length;
    const registry = new MediaAssetRegistry({ version: 1, assets: [a] }), review = approval(a), plan = pcmPlan();
    plan.cues[0].sourceHash = a.contentHash;
    const options = { ffmpeg, voiceFile, plan, registry, approvals: [review], mediaRoot: root };
    const result = await mixAudio(options), repeat = await mixAudio(options);
    assert(result.qa.passed);
    assert.equal(result.qa.sampleRate, 48000);
    assert.equal(result.qa.channels, 2);
    assert(Math.abs(result.qa.duration - 1) < 1 / 48000);
    assert(repeat.cacheHit);
    assert.equal(repeat.fingerprint, result.fingerprint);
    assert.equal(contentHash(await readFile(sfxFile)), a.contentHash);
    const changed = structuredClone(plan);
    changed.cues[0].gainDb = -25;
    const other = await mixAudio({ ...options, plan: changed });
    assert.notEqual(other.fingerprint, result.fingerprint);
    assert.notEqual(other.output, result.output);
    // The changed fingerprint may already exist from an earlier run; it must never reuse the original key.
    await writeFile(result.output, "corrupted cache fixture");
    const recovered = await mixAudio(options);
    assert.equal(recovered.cacheHit, false);
    assert(recovered.qa.passed);
    await assert.rejects(mixAudio({ ...options, approvals: [] }));
    await writeFile(sfxFile, "changed");
    await assert.rejects(mixAudio(options), /MEDIA_HASH_MISMATCH/);
    await writeFile(soundOutput("controlled-integration.json"), JSON.stringify({ passed: true, syntheticFixtureOnly: true, productionHumanApproval: false, qa: result.qa, repeatCacheHit: repeat.cacheHit, invalidationVerified: true, originalUnchangedBeforeTamperTest: true }, null, 2));
});
